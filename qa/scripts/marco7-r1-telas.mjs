// Marco 7 (0.13.0), rodada 1: fim (FI1 com gesto, JC), créditos (FI3), explorar a casa (EX1 a EX5), título (captura). Teclado (tecla 90 ms). Só observa.
import { lancar, novoContexto, abrirJogo, tecla, lerTextos, sleep } from './lib.mjs';
import { estado } from './lib-rota.mjs';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { join, dirname, resolve } from 'node:path';
const RAIZ = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const EVID = join(RAIZ, 'qa', 'evidencias', 'marco7-r1');
const url = pathToFileURL(resolve(RAIZ, 'dist-qa', 'index.html')).href;
const b = await lancar();
const log = (id, ok, nota = '') => console.log(`${ok ? 'OK   ' : 'FALHA'} ${id} :: ${nota}`);
const ev = (a) => (a?.ultimosEventos ?? []).map((e) => e.evento + (e.variante ? '/' + e.variante : '')).join(' ');
const c = await novoContexto(b, { url, origem: url, rotulo: 'tel' });
const p = await abrirJogo(c, url);
const est = async () => { try { return await estado(p); } catch { return null; } };
await p.screenshot({ path: join(EVID, 'titulo-m7.png') });
await tecla(p, 'KeyZ', { ms: 90, pausa: 500 }); // gesto: libera o áudio
await p.evaluate(() => window.__partidaConcluida('lolo', false));
await p.evaluate(() => window.__irPara('Fim', {}));
await sleep(3500);
const af = (await est())?.audio;
await p.screenshot({ path: join(EVID, 'fim-tela.png') });
const txtF = (await lerTextos(p)).map((t) => t.t).join(' ').replace(/\s+/g, ' ');
const jc = (af?.ultimosEventos ?? []).filter((e) => e.evento === 'JC').length;
log('FI1 tela de fim: JC toca uma vez ao abrir (gancho)', jc === 1, `JC=${jc} ; ${ev(af).slice(-80)}`);
log('FI1 texto de fim.obrigado presente (3 linhas, sem nomes)', /Obrigado por jogar/.test(txtF), txtF.slice(0, 120));
await tecla(p, 'KeyZ', { ms: 90, pausa: 900 });
const t2 = (await lerTextos(p)).map((t) => t.t).join(' ').replace(/\s+/g, ' ');
await p.screenshot({ path: join(EVID, 'creditos-menu.png') });
log('FI3 créditos: "Voltar ao título" e "Explorar a casa" no menu', /Voltar ao título/.test(t2) && /Explorar a casa/.test(t2), t2.slice(0, 120));
await tecla(p, 'ArrowDown', { ms: 90, pausa: 400 });
await tecla(p, 'KeyZ', { ms: 90, pausa: 1500 });
const e = await est();
log('EX1 explorar a casa: sala, tile (3,7), Nick acordado', e?.mapa === 'sala' && e?.tileX === 3 && e?.tileY === 7 && e?.nick?.estado === 'acordado', `mapa=${e?.mapa} tile=${e?.tileX},${e?.tileY} nick=${e?.nick?.estado}`);
await p.screenshot({ path: join(EVID, 'explorar-entrada.png') });
const al = await p.evaluate(() => window.__alvosDeToque());
log('EX2 sem "?" (Casa:Image ausente)', !al.some((a) => a.nome === 'Casa:Image'), al.map((a) => a.nome).filter((n) => n.startsWith('icone') || n.startsWith('Casa')).join(','));
await tecla(p, 'KeyH', { ms: 90, pausa: 500 });
log('EX2 H não abre dica', !((await est())?.dicaAberta), `dicaAberta=${(await est())?.dicaAberta}`);
await tecla(p, 'KeyP', { ms: 90, pausa: 600 });
const e3 = await est();
log('EX4 P abre a pausa', e3?.pausa?.aberta === true, JSON.stringify(e3?.pausa));
await p.screenshot({ path: join(EVID, 'explorar-pausa.png') });
for (let i = 0; i < 3; i++) await tecla(p, 'ArrowDown', { ms: 90, pausa: 300 });
await tecla(p, 'KeyZ', { ms: 90, pausa: 500 });
const e4 = await est();
log('EX4 "Voltar ao título" pede confirmação com "Não" em foco', e4?.pausa?.visao === 'confirmacao' && e4?.pausa?.foco === 1, JSON.stringify(e4?.pausa));
await p.screenshot({ path: join(EVID, 'explorar-confirmacao.png') });
await tecla(p, 'KeyZ', { ms: 90, pausa: 500 });
const e5 = await est();
log('EX4 "Não" volta à pausa', e5?.pausa?.visao === 'pausa', JSON.stringify(e5?.pausa));
await tecla(p, 'Escape', { ms: 90, pausa: 500 });
await tecla(p, 'KeyX', { ms: 90, pausa: 600 });
const e6 = await est();
log('EX5 X (farejar) no explorar sem seta', !e6?.farejo?.ativo, `farejo=${e6?.farejo?.ativo}`);
await c.close(); await b.close();
