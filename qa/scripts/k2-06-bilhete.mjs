// K2-06: barra "Z: avançar  X: fechar" no bilhete (p1 e última página). Rota real (lib-rota) + build de QA.
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { RAIZ, abrirJogo, capturar, criarRelatorio, lancar, lerTextos, limparTextos, novoContexto, sleep, tecla, irAteHall } from './lib.mjs';
import { estado, irPara, ladoDe, esperarParado, objeto } from './lib-rota.mjs';

const url = pathToFileURL(join(RAIZ, 'dist-qa', 'index.html')).href;
const rel = criarRelatorio('k2-06-bilhete');
const browser = await lancar();
const ctx = await novoContexto(browser, { url, rotulo: 'K2-06' });
const page = await abrirJogo(ctx, url);
await irAteHall(page, 0);
const e = await esperarParado(page);
const obj = objeto('hall', 'bilhete', 'bilhete.pista');
const lado = ladoDe('hall', 'bilhete', 'bilhete.pista', e);
const antes = { x: lado.x + (lado.x - obj.x), y: lado.y + (lado.y - obj.y) };
if (antes.x >= 0 && antes.x < 3 && antes.y >= 0 && antes.y < 4) await irPara(page, 'hall', antes.x, antes.y);
await irPara(page, 'hall', lado.x, lado.y);
console.log('estado antes de examinar', JSON.stringify(await estado(page)));
await limparTextos(page);
await tecla(page, 'z');
await sleep(300);
const p1 = await lerTextos(page);
await capturar(page, 'k2-06-bilhete-p1');
const barrasP1 = p1.map((x) => x.t).filter((t) => /Z|X|avan|fech/.test(t));
console.log('p1 textos barra:', JSON.stringify(barrasP1));
await limparTextos(page);
await tecla(page, 'z');
await sleep(300);
const p2 = await lerTextos(page);
await capturar(page, 'k2-06-bilhete-p2');
const barrasP2 = p2.map((x) => x.t).filter((t) => /Z|X|avan|fech/.test(t));
console.log('p2 textos barra:', JSON.stringify(barrasP2));
await limparTextos(page);
await tecla(page, 'z');
await sleep(300);
const fim = await estado(page);
const t3 = await lerTextos(page);
rel.caso('K2-06', barrasP1.includes('Z: avançar  X: fechar') && barrasP2.includes('Z: avançar  X: fechar') ? 'OK' : 'FALHOU', `barras p1=${JSON.stringify(barrasP1)} p2=${JSON.stringify(barrasP2)}; após Z final travado=${fim?.travado}`);
rel.dado('fechou', !fim?.travado);
rel.salvar();
await ctx.close();
await browser.close();
